// while loop
//syntax
// while (condition) {

// }

let i = 0;
while (i < 10) {
  //   console.log(`${i}th iterations is going on`);
  i++;
}

let myArray = ["IronMan", "Captain America", "Hulk", "Thor"];
let arr = 0;
while (arr < myArray.length) {
  //   console.log(`Marvel hero: ${myArray[arr]}`);
  arr++;
}

// do while loop
//syntax
// do{}while();

let score = 1;
do {
  //   console.log(`The score is: ${score}`);
  score++;
} while (score <= 10);

let score1 = 11;
